export type TranslationKey = keyof (typeof translations)["ja"];

export const DEFAULT_UI_LANGUAGE = "ja" as const;

export function translate(
  language: "ja" | "en",
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  // translations[language][key]'s type already guarantees a string: `en` and
  // `ja` must share an identical key set for this file to type-check at all
  // (TranslationKey is `keyof (typeof translations)["ja"]`), so a missing key
  // in either dictionary would be a compile error, not a runtime gap.
  let value: string = translations[language][key];
  for (const [name, replacement] of Object.entries(values)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

